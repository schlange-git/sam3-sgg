"""
Cached Pair Dataset: Loads precomputed cache files
"""
import os
from typing import Dict, List
import torch
from torch.utils.data import Dataset


class CachedPairDataset(Dataset):
    """
    Dataset for loading precomputed pair cache files
    
    Each cache file contains:
    - geom_feat: [P, Gd] float32
    - pair_label: [P] int64
    - pair_mask: [P] uint8
    """
    
    def __init__(self, cache_dir: str) -> None:
        """
        Args:
            cache_dir: Directory containing .pt cache files
        """
        self.cache_dir = cache_dir
        self.files: List[str] = []
        
        for fn in sorted(os.listdir(cache_dir)):
            if fn.endswith(".pt"):
                self.files.append(os.path.join(cache_dir, fn))
        
        if len(self.files) == 0:
            raise RuntimeError(f"No .pt cache files found in: {cache_dir}")
        
        print(f"Loaded {len(self.files)} cache files from {cache_dir}")
    
    def __len__(self) -> int:
        return len(self.files)
    
    def __getitem__(self, idx: int) -> Dict[str, torch.Tensor]:
        # weights_only=False is needed for PyTorch 2.6+ when loading files with numpy arrays
        # These cache files are generated by our own code, so they are trusted
        pack = torch.load(self.files[idx], map_location="cpu", weights_only=False)
        
        # Convert numpy arrays to torch tensors
        geom_feat = torch.from_numpy(pack["geom_feat"]).float()  # [P,Gd]
        pair_label = torch.from_numpy(pack["pair_label"]).long()  # [P]
        pair_mask = torch.from_numpy(pack["pair_mask"]).bool()    # [P]
        
        result = {
            "geom_feat": geom_feat,
            "pair_label": pair_label,
            "pair_mask": pair_mask,
        }
        
        # Include pair_idx if available (for evaluation)
        if "pair_idx" in pack:
            result["pair_idx"] = torch.from_numpy(pack["pair_idx"]).long()  # [P, 2]
        
        return result


def collate_cached(batch: List[Dict[str, torch.Tensor]]) -> Dict[str, torch.Tensor]:
    """
    Collate function for cached pairs
    Since P is fixed, we can just stack
    
    Returns:
        {
            "geom_feat": [B,P,Gd],
            "pair_label": [B,P],
            "pair_mask": [B,P],
            "pair_idx": [B,P,2] (optional),
        }
    """
    geom_feat = torch.stack([b["geom_feat"] for b in batch], dim=0)      # [B,P,Gd]
    pair_label = torch.stack([b["pair_label"] for b in batch], dim=0)    # [B,P]
    pair_mask = torch.stack([b["pair_mask"] for b in batch], dim=0)      # [B,P]
    
    result = {
        "geom_feat": geom_feat,
        "pair_label": pair_label,
        "pair_mask": pair_mask,
    }
    
    # Include pair_idx if available
    if "pair_idx" in batch[0]:
        result["pair_idx"] = torch.stack([b["pair_idx"] for b in batch], dim=0)  # [B,P,2]
    
    return result

