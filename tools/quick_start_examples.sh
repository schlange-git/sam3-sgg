#!/bin/bash
#
# SpeaQ 快速启动示例集合
# 提供常用场景的一键运行命令
#

# ============================================================================
# 示例 1: 快速验证流程 (推荐首次使用)
# ============================================================================
example_1_quick_test() {
    echo "示例 1: 快速验证 (10图 × 500迭代)"
    ./run_full_pipeline.sh --iters 500 --overfit 10
}

# ============================================================================
# 示例 2: 标准 10-clip 过拟合
# ============================================================================
example_2_standard_overfit() {
    echo "示例 2: 标准过拟合 (10图 × 2000迭代)"
    ./run_full_pipeline.sh --iters 2000 --overfit 10 --batch-size 2
}

# ============================================================================
# 示例 3: 充分训练的过拟合
# ============================================================================
example_3_full_overfit() {
    echo "示例 3: 充分训练 (10图 × 5000迭代)"
    ./run_full_pipeline.sh --iters 5000 --overfit 10 --batch-size 4
}

# ============================================================================
# 示例 4: 多 GPU 加速
# ============================================================================
example_4_multi_gpu() {
    echo "示例 4: 多GPU训练 (2 GPU, 10图 × 10000迭代)"
    ./run_full_pipeline.sh --gpus 2 --iters 10000 --batch-size 4
}

# ============================================================================
# 示例 5: 小批量测试不同迭代次数
# ============================================================================
example_5_iteration_sweep() {
    echo "示例 5: 迭代次数对比实验"
    echo "运行 500, 1000, 2000 三个实验..."
    
    ./run_full_pipeline.sh --iters 500 --overfit 10
    ./run_full_pipeline.sh --iters 1000 --overfit 10
    ./run_full_pipeline.sh --iters 2000 --overfit 10
    
    echo ""
    echo "实验完成！现在对比结果..."
    python compare_results.py output_pipeline_*/finetune_*
}

# ============================================================================
# 主菜单
# ============================================================================
show_menu() {
    echo ""
    echo "════════════════════════════════════════════════════════"
    echo "  SpeaQ 快速启动示例"
    echo "════════════════════════════════════════════════════════"
    echo ""
    echo "选择一个示例运行:"
    echo ""
    echo "  1) 快速验证 (10图 × 500迭代) - 推荐首次使用"
    echo "  2) 标准过拟合 (10图 × 2000迭代)"
    echo "  3) 充分训练 (10图 × 5000迭代)"
    echo "  4) 多GPU训练 (2 GPU × 10000迭代)"
    echo "  5) 迭代次数对比实验 (500/1000/2000)"
    echo ""
    echo "  h) 查看全链路脚本帮助"
    echo "  q) 退出"
    echo ""
}

# 主循环
main() {
    while true; do
        show_menu
        read -p "请选择 [1-5, h, q]: " choice
        
        case $choice in
            1)
                example_1_quick_test
                break
                ;;
            2)
                example_2_standard_overfit
                break
                ;;
            3)
                example_3_full_overfit
                break
                ;;
            4)
                example_4_multi_gpu
                break
                ;;
            5)
                example_5_iteration_sweep
                break
                ;;
            h|H)
                ./run_full_pipeline.sh --help
                ;;
            q|Q)
                echo "退出"
                exit 0
                ;;
            *)
                echo "无效选择，请重试"
                ;;
        esac
    done
}

# 如果脚本被直接运行（不是被 source）
if [ "${BASH_SOURCE[0]}" == "${0}" ]; then
    main
fi
